function get_translations($language = 'en') {
    global $translations;
    if (!isset($translations[$language])) {
        $language = 'en';
    }
    return $translations[$language];
}

function t($key, $language = 'en', $args = []) {
    $translations_set = get_translations($language);
    $text = $translations_set[$key] ?? $key;
    
    if (!empty($args)) {
        foreach ($args as $i => $arg) {
            $text = str_replace('%' . ($i + 1), htmlspecialchars($arg), $text);
        }
        $text = str_replace('%s', reset($args), $text);
    }
    
    return $text;
}
